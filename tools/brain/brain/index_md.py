"""Regenerate knowledge/INDEX.md: by type (newest first), by tag, by owner.
One line per file: date, title, owner, status, relative link. Also lists catalog/datasets/*.md
under type dataset so the index is the one table of contents."""

from __future__ import annotations

import os
from collections import defaultdict
from pathlib import Path

from brain.build import ROOT, _split_frontmatter

INDEX_MD = ROOT / "knowledge" / "INDEX.md"
TYPE_ORDER = ["context", "decision", "meeting", "research-log", "agent-log", "note", "dataset"]


def _entries(root: Path = ROOT) -> list[dict]:
    files = [
        p
        for p in (root / "knowledge").rglob("*.md")
        if p.name != "INDEX.md"
        and "templates" not in p.relative_to(root).parts
        and ".obsidian" not in p.parts
    ]
    files += list((root / "catalog" / "datasets").glob("*.md"))
    out = []
    for p in sorted(files):
        fm, _ = _split_frontmatter(p.read_text(encoding="utf-8", errors="replace"))
        if not fm:
            continue
        out.append(
            {
                "path": p,
                "rel": Path(os.path.relpath(p, INDEX_MD.parent)).as_posix(),
                "type": str(fm.get("type", "note")),
                "title": str(fm.get("title", p.stem)),
                "date": str(fm.get("date", "")),
                "owner": str(fm.get("owner", "")),
                "status": str(fm.get("status", "")),
                "tags": [str(t) for t in (fm.get("tags") or [])],
                "private": fm.get("private") is True,
            }
        )
    return out


def _line(e: dict) -> str:
    status = f" · {e['status']}" if e["status"] else ""
    return f"- {e['date']} · [{e['title']}]({e['rel']}) · @{e['owner']}{status}"


def render(root: Path = ROOT) -> str:
    entries = [e for e in _entries(root) if not e["private"]]
    by_type: dict[str, list[dict]] = defaultdict(list)
    by_tag: dict[str, list[dict]] = defaultdict(list)
    by_owner: dict[str, list[dict]] = defaultdict(list)
    for e in entries:
        by_type[e["type"]].append(e)
        by_owner[e["owner"]].append(e)
        for t in e["tags"]:
            by_tag[t].append(e)
    lines = [
        "# Knowledge index",
        "",
        "Generated by `just index`; do not edit by hand. One line per file: date, title, owner, status.",
        f"{len(entries)} files.",
        "",
        "## By type",
        "",
    ]
    types = [t for t in TYPE_ORDER if t in by_type] + sorted(set(by_type) - set(TYPE_ORDER))
    for t in types:
        lines += [f"### {t}", ""]
        lines += [
            _line(e)
            for e in sorted(by_type[t], key=lambda e: (e["date"], e["title"]), reverse=True)
        ]
        lines.append("")
    lines += ["## By tag", ""]
    for t in sorted(by_tag):
        lines += [f"### {t}", ""]
        lines += [
            _line(e) for e in sorted(by_tag[t], key=lambda e: (e["date"], e["title"]), reverse=True)
        ]
        lines.append("")
    lines += ["## By owner", ""]
    for o in sorted(by_owner):
        lines += [f"### @{o}", ""]
        lines += [
            _line(e)
            for e in sorted(by_owner[o], key=lambda e: (e["date"], e["title"]), reverse=True)
        ]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write(root: Path = ROOT) -> Path:
    INDEX_MD.write_text(render(root), encoding="utf-8")
    return INDEX_MD
