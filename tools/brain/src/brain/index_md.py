"""Render the knowledge index (``repo.index_md``): by type (newest first), by tag, by owner.
One line per file: date, title, owner, status, relative link. Dataset READMEs are listed under
type dataset so the index is the one table of contents."""

from __future__ import annotations

import os
from collections import defaultdict
from pathlib import Path

from brain.build import split_frontmatter
from brain.repo import Repo

TYPE_ORDER = ["context", "decision", "meeting", "research-log", "agent-log", "note", "dataset"]


def entries(repo: Repo) -> list[dict]:
    kn = repo.path(repo.knowledge)
    files = [
        p
        for p in kn.rglob("*.md")
        if p.resolve() != repo.index_md_path.resolve()
        and not any(s in p.relative_to(repo.root).parts for s in repo.skip_parts)
    ]
    files += list(repo.path(repo.datasets).glob("*.md"))
    base = repo.index_md_path.parent
    out = []
    for p in sorted(files):
        fm, _ = split_frontmatter(p.read_text(encoding="utf-8", errors="replace"))
        if not fm:
            continue
        out.append(
            {
                "path": p,
                "rel": Path(os.path.relpath(p, base)).as_posix(),
                "type": str(fm.get("type", "note")),
                "title": str(fm.get("title", p.stem)),
                "date": str(fm.get("date", "")),
                "owner": str(fm.get("owner", "")),
                "status": str(fm.get("status", "")),
                "tags": [str(t) for t in (fm.get("tags") or [])],
                "private": fm.get("private") is True,
            }
        )
    return out


def _line(e: dict) -> str:
    status = f" · {e['status']}" if e["status"] else ""
    return f"- {e['date']} · [{e['title']}]({e['rel']}) · @{e['owner']}{status}"


def _newest(items: list[dict]) -> list[dict]:
    return sorted(items, key=lambda e: (e["date"], e["title"]), reverse=True)


def render(repo: Repo, *, command: str = "just index") -> str:
    public = [e for e in entries(repo) if not e["private"]]
    by_type: dict[str, list[dict]] = defaultdict(list)
    by_tag: dict[str, list[dict]] = defaultdict(list)
    by_owner: dict[str, list[dict]] = defaultdict(list)
    for e in public:
        by_type[e["type"]].append(e)
        by_owner[e["owner"]].append(e)
        for t in e["tags"]:
            by_tag[t].append(e)
    lines = [
        "# Knowledge index",
        "",
        f"Generated by `{command}`; do not edit by hand. One line per file: date, title, owner, status.",
        f"{len(public)} files.",
        "",
        "## By type",
        "",
    ]
    types = [t for t in TYPE_ORDER if t in by_type] + sorted(set(by_type) - set(TYPE_ORDER))
    for t in types:
        lines += [f"### {t}", "", *[_line(e) for e in _newest(by_type[t])], ""]
    lines += ["## By tag", ""]
    for t in sorted(by_tag):
        lines += [f"### {t}", "", *[_line(e) for e in _newest(by_tag[t])], ""]
    lines += ["## By owner", ""]
    for o in sorted(by_owner):
        lines += [f"### @{o}", "", *[_line(e) for e in _newest(by_owner[o])], ""]
    return "\n".join(lines).rstrip() + "\n"


def write(repo: Repo, *, command: str = "just index") -> Path:
    repo.index_md_path.parent.mkdir(parents=True, exist_ok=True)
    repo.index_md_path.write_text(render(repo, command=command), encoding="utf-8")
    return repo.index_md_path
