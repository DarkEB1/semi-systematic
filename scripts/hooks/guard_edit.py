"""PreToolUse hook for Edit/Write: block edits to files that are generated, secret or frozen.

Stdlib only (runs on the host python). Exit 2 with the reason on stderr blocks the edit.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

FROZEN_RE = re.compile(r"^status:\s*final\s*$", re.M)


def frozen_experiment(path: Path) -> Path | None:
    """The experiment folder that contains ``path`` if its results.md says ``status: final``."""
    for parent in [path, *path.parents]:
        if parent.parent.name == "experiments" and (parent / "results.md").exists():
            text = (parent / "results.md").read_text(encoding="utf-8", errors="replace")
            return parent if FROZEN_RE.search(text) else None
    return None


def reason_for(raw: str, cwd: Path) -> str | None:
    path = Path(raw)
    rel = (
        path.relative_to(cwd).as_posix()
        if path.is_absolute() and cwd in path.parents
        else path.as_posix()
    )
    name = path.name
    if name.startswith(".env") and name != ".env.example":
        return f"{name} is hand-maintained and secret; never written by an agent"
    if rel.endswith("knowledge/INDEX.md"):
        return "knowledge/INDEX.md is generated by `just index`"
    if name == "uv.lock":
        return "uv.lock is generated by `uv lock`"
    folder = frozen_experiment(path if path.is_absolute() else cwd / path)
    if folder is not None:
        return f"{folder.name} is frozen (results.md says status: final); start a new experiment with parent:"
    return None


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return 0
    raw = (payload.get("tool_input") or {}).get("file_path") or (
        payload.get("tool_input") or {}
    ).get("notebook_path")
    if not raw:
        return 0
    cwd = Path(payload.get("cwd") or ".").resolve()
    reason = reason_for(str(raw), cwd)
    if reason:
        print(f"blocked by scripts/hooks/guard_edit.py: {reason}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
